"""Single source of truth: one row per post, every channel.

Every collector writes rows in this shape. Every downstream step reads only this.
"""
from __future__ import annotations

import hashlib
from dataclasses import dataclass, asdict, field
from datetime import date
from typing import Optional

COLUMNS = [
    "post_id",          # stable id: channel + url/hash
    "channel",          # x | linkedin | telegram
    "account",          # Re7 Capital | Re7 Labs
    "date",             # ISO date (YYYY-MM-DD)
    "date_precision",   # exact | approx
    "url",
    "text",             # post text (may be empty for legacy captures)
    "format",           # text | link | image | video | repost | quote | thread | document
    "likes",
    "reposts",
    "comments",
    "views",            # blank where the channel does not expose it
    "theme",            # filled by analyse step (taxonomy.THEMES)
    "label_source",     # heuristic | claude
    "names_person",     # True/False: tags or names a specific person
    "names_partner",    # True/False: tags or names a partner firm / outlet
    "is_reply",         # replies/disclaimers excluded from stats
    "experiment_tag",   # set when the post was generated by this system
    "source_doc",       # the Re7 research/Weekly the post repurposes, if any
    "collected_via",    # seed | telegram_public | apify_x | apify_linkedin | csv_import
    "engagement_score", # likes + 2*reposts + 3*comments
    "engagement_index", # engagement_score / channel median (main posts only)
]

CHANNELS = ("x", "linkedin", "telegram")
ACCOUNTS = ("Re7 Capital", "Re7 Labs")


def make_post_id(channel: str, url: str, text: str, date_str: str) -> str:
    key = url.strip().lower() if url else f"{text[:80]}|{date_str}"
    return f"{channel}:{hashlib.sha1(key.encode()).hexdigest()[:12]}"


def engagement_score(likes, reposts, comments) -> float:
    def n(v):
        try:
            return float(v) if v not in (None, "") else 0.0
        except (TypeError, ValueError):
            return 0.0
    return n(likes) + 2 * n(reposts) + 3 * n(comments)


@dataclass
class Post:
    channel: str
    account: str
    date: str
    url: str = ""
    text: str = ""
    format: str = "text"
    likes: Optional[float] = None
    reposts: Optional[float] = None
    comments: Optional[float] = None
    views: Optional[float] = None
    date_precision: str = "exact"
    theme: str = ""
    label_source: str = ""
    names_person: Optional[bool] = None
    names_partner: Optional[bool] = None
    is_reply: bool = False
    experiment_tag: str = ""
    source_doc: str = ""
    collected_via: str = "seed"
    post_id: str = field(default="")
    engagement_score: float = 0.0
    engagement_index: Optional[float] = None

    def __post_init__(self):
        assert self.channel in CHANNELS, self.channel
        if not self.post_id:
            self.post_id = make_post_id(self.channel, self.url, self.text, self.date)
        self.engagement_score = engagement_score(self.likes, self.reposts, self.comments)

    def row(self) -> dict:
        d = asdict(self)
        return {c: d.get(c) for c in COLUMNS}
